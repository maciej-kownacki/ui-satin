// Reads tokens.json (the source of truth) and writes:
//   packages/ui/src/styles/theme.css   shadcn v4 / Tailwind v4 theme for code
//   figma-payload.json        flat list the Figma script consumes (--figma <path>)
// Usage: node tokens/build.mjs [--figma <path>]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const COLLECTIONS = ['primitives', 'theme', 'tone', 'radius', 'border-width', 'spacing', 'typography'];
const modesOf = (c) => tokens[c].$extensions?.['com.satin']?.modes ?? (c === 'theme' ? ['Light', 'Dark'] : ['Value']);

const flat = new Map();
(function walk(node, path) {
  if (node && typeof node === 'object' && '$value' in node) {
    flat.set(path.join('.'), { path, ...node, ext: node.$extensions?.['com.satin'] ?? {} });
    return;
  }
  for (const [k, v] of Object.entries(node)) if (!k.startsWith('$')) walk(v, [...path, k]);
})(tokens, []);

const isAlias = (v) => typeof v === 'string' && /^\{.+\}$/.test(v);
const target = (v) => flat.get(v.slice(1, -1));
const resolve = (v) => (isAlias(v) ? resolve(target(v).$value) : v);
const dim = (v) => (typeof v === 'object' ? v.value : v);
const cssVar = (t) => t.ext.css;

/** Where dark mode is on: either of these on any parent. */
const DARK = ['.dark', '[data-theme="dark"]'];
/** Follows the OS: dark under prefers-color-scheme: dark, light otherwise. */
const SYSTEM = '[data-theme="system"]';

// ---------- Figma payload ----------
function figmaPayload() {
  const cols = Object.fromEntries(COLLECTIONS.map((c) => [c, {
    modes: modesOf(c),
    hiddenFromPublishing: c === 'primitives',
    vars: [],
  }]));
  const figmaValue = (v) => {
    if (isAlias(v)) {
      const t = target(v);
      return { alias: { collection: t.path[0], name: t.path.slice(1).join('/') } };
    }
    return typeof v === 'object' ? v.value : v;
  };
  for (const t of flat.values()) {
    const col = t.path[0];
    if (!cols[col] || t.ext.figma === 'not-a-variable') continue;
    const type = { color: 'COLOR', dimension: 'FLOAT', fontWeight: 'FLOAT', fontFamily: 'STRING' }[t.$type];
    const css = cssVar(t);
    const values = { [cols[col].modes[0]]: figmaValue(t.$value) };
    if (t.ext.modes) for (const [m, v] of Object.entries(t.ext.modes)) values[m] = figmaValue(v);
    cols[col].vars.push({
      name: t.path.slice(1).join('/'),
      type,
      scopes: t.ext.scopes ?? [],
      web: css.startsWith('--') ? `var(${css})` : css,
      description: t.$description ?? '',
      values,
    });
  }
  const varRef = (v) => {
    const t = target(v);
    return { collection: t.path[0], name: t.path.slice(1).join('/') };
  };
  const textStyles = Object.entries(tokens.styles.text).map(([k, s]) => ({
    name: `text/${k}`,
    description: s.$description,
    fontFamily: varRef(s.$value.fontFamily),
    fontSize: varRef(s.$value.fontSize),
    fontWeight: varRef(s.$value.fontWeight),
    lineHeight: varRef(s.$value.lineHeight),
    letterSpacingPercent: resolve(s.$value.letterSpacing).value * 100,
  }));
  const effectStyles = Object.entries(tokens.styles.effect).filter(([k]) => !k.startsWith('$')).map(([k, s]) => ({
    name: `shadow/${k.replace('shadow-', '')}`,
    description: s.$description,
    layers: s.$value.map((l) => ({
      color: varRef(l.color),
      x: dim(l.offsetX), y: dim(l.offsetY), blur: dim(l.blur), spread: dim(l.spread), inset: !!l.inset,
    })),
  }));
  return { collections: cols, textStyles, effectStyles };
}

// ---------- globals.css ----------
function css() {
  const all = [...flat.values()];
  const of = (col) => all.filter((t) => t.path[0] === col);
  const ref = (v) => (isAlias(v) ? `var(${cssVar(target(v))})` : typeof v === 'object' ? `${v.value}${v.unit}` : v);
  const px = (v) => `${dim(resolve(v))}px`;
  const L = [];
  L.push('/* Generated by tokens/build.mjs from tokens/tokens.json. Do not edit by hand. */');
  // Dark mode: the `dark` class or data-theme="dark" on any parent, or data-theme="system" to
  // follow the OS (prefers-color-scheme). The `dark:` variant and the token blocks below agree.
  L.push(
    '',
    '@custom-variant dark {',
    `  &:is(${DARK.map((s) => `${s} *`).join(', ')}) {`,
    '    @slot;',
    '  }',
    '  @media (prefers-color-scheme: dark) {',
    `    &:is(${SYSTEM} *) {`,
    '      @slot;',
    '    }',
    '  }',
    '}',
    '',
  );

  L.push('/* Primitives: hex, same as the Figma `primitives` collection. They override Tailwind\'s oklch palette. */');
  L.push('@theme static {');
  for (const t of of('primitives')) L.push(`  ${cssVar(t)}: ${t.$value};`);
  L.push('  --spacing: 4px;', '}', '');

  const theme = of('theme');
  const block = (sel, pick) => {
    L.push(`${sel} {`);
    if (sel === ':root') {
      for (const t of of('radius').filter((t) => cssVar(t) === '--radius')) L.push(`  --radius: ${px(t.$value)};`);
    }
    for (const t of theme) L.push(`  ${cssVar(t)}: ${ref(pick(t))};`);
    if (sel === ':root') {
      for (const t of of('spacing').filter((t) => t.path[1] === 'size')) L.push(`  ${cssVar(t)}: ${px(t.$value)};`);
    }
    L.push('}', '');
  };
  block(':root', (t) => t.$value);
  // A theme token without a Dark mode (a colour both themes share) keeps its one value.
  const dark = (t) => t.ext.modes?.Dark ?? t.$value;
  block(DARK.join(', '), dark);
  // The same values when data-theme="system" and the OS is dark.
  {
    const start = L.length;
    block(SYSTEM, dark);
    const lines = L.splice(start);
    while (lines.at(-1) === '') lines.pop();
    L.push('@media (prefers-color-scheme: dark) {', ...lines.map((l) => (l ? `  ${l}` : l)), '}', '');
  }

  // Tone: one block per mode, picked with data-tone (default = first mode).
  const tone = of('tone');
  modesOf('tone').forEach((m, i) => {
    L.push(i === 0 ? `:root, [data-tone="${m.toLowerCase()}"] {` : `[data-tone="${m.toLowerCase()}"] {`);
    for (const t of tone) L.push(`  ${cssVar(t)}: ${ref(i === 0 ? t.$value : t.ext.modes[m])};`);
    L.push('}', '');
  });

  // Corners and type sizes stay variables in the utilities (plain @theme, not inline), so a
  // theme can rescale them at runtime: rounded-xl is var(--radius-xl), text-sm var(--text-sm).
  L.push('@theme static {');
  for (const t of of('radius').filter((t) => cssVar(t) !== '--radius')) {
    L.push(`  ${cssVar(t)}: ${isAlias(t.$value) ? `var(${cssVar(target(t.$value))})` : px(t.$value)};`);
  }
  {
    const tracking = resolve('{typography.tracking.tracking-tight}');
    for (const t of of('typography').filter((t) => t.path[1] === 'text')) {
      const size = dim(t.$value);
      const lh = dim(flat.get(`typography.leading.${t.path[2]}--line-height`).$value);
      L.push(`  ${cssVar(t)}: ${size}px;`);
      L.push(`  ${cssVar(t)}--line-height: ${Math.round((lh / size) * 1000) / 1000};`);
      L.push(`  ${cssVar(t)}--letter-spacing: ${tracking.value}${tracking.unit};`);
    }
  }
  // Stroke widths: Tailwind's border-*, border-x… and divide-* read --default-border-width, and
  // border-strong is border-width/strong. A width under 1px is written as what browsers draw for
  // a border of that width (whole device pixels, rounded down, at least one), screen by screen,
  // so a box-shadow stroke, which browsers don't snap, is as crisp as a border: 0.75 is 1px on
  // 1x screens, 0.5px on 2x, 0.667px on 3x.
  const snap = (v, dpr) => Math.round((Math.max(1, Math.floor(v * dpr + 1e-9)) / dpr) * 1000) / 1000;
  const widths = of('border-width');
  for (const t of widths) L.push(`  ${cssVar(t)}: ${snap(dim(t.$value), 1)}px;`);
  L.push('  --default-border-width: var(--border-width-default);');
  L.push('}', '');
  for (const dpr of [2, 3]) {
    const lines = widths.filter((t) => snap(dim(t.$value), dpr) !== snap(dim(t.$value), 1)).map((t) => `    ${cssVar(t)}: ${snap(dim(t.$value), dpr)}px;`);
    if (lines.length) L.push(`@media (min-resolution: ${dpr}dppx) {`, '  :root {', ...lines, '  }', '}', '');
  }

  L.push('@theme inline {');
  for (const t of [...theme, ...of('tone')].filter((t) => !cssVar(t).startsWith('--effect-'))) {
    L.push(`  --color-${cssVar(t).slice(2)}: var(${cssVar(t)});`);
  }
  L.push('');
  for (const t of of('spacing').filter((t) => t.path[1] === 'size')) {
    L.push(`  --spacing-${cssVar(t).slice(2)}: var(${cssVar(t)});`);
  }
  L.push('');
  // The family by its own name, then as the variable font packages register it
  // (@fontsource-variable/geist declares "Geist Variable"), so either install just works.
  const fam = (t) => `"${t.$value}", "${t.$value} Variable"`;
  for (const t of of('typography').filter((t) => t.$type === 'fontFamily')) {
    const fallback = cssVar(t) === '--font-mono' ? 'ui-monospace, monospace' : 'ui-sans-serif, system-ui, sans-serif';
    L.push(`  ${cssVar(t)}: ${fam(t)}, ${fallback};`);
  }
  for (const t of of('typography').filter((t) => t.$type === 'fontWeight')) L.push(`  ${cssVar(t)}: ${t.$value};`);
  const tracking = resolve('{typography.tracking.tracking-tight}');
  L.push(`  --tracking-tight: ${tracking.value}${tracking.unit};`);
  L.push('');
  for (const [k, s] of Object.entries(tokens.styles.effect)) {
    if (k.startsWith('$')) continue;
    const layers = s.$value.map((l) =>
      `${l.inset ? 'inset ' : ''}${dim(l.offsetX)}px ${dim(l.offsetY)}px ${dim(l.blur)}px ${dim(l.spread)}px ${ref(l.color)}`);
    L.push(`  --${k}: ${layers.join(', ')};`);
  }
  L.push('}', '');

  // The base rules (borders, body text, focus ring) live in packages/ui/src/styles/base.css.
  return L.join('\n') + '\n';
}

writeFileSync(join(here, '../packages/ui/src/styles/theme.css'), css());
const fi = process.argv.indexOf('--figma');
if (fi > -1) writeFileSync(process.argv[fi + 1], JSON.stringify(figmaPayload()));
console.log(`tokens: ${flat.size}`);
