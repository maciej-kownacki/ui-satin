/**
 * The npm build, in order (see build/prefix.mjs for why Satin ships prefixed):
 *
 * 1. classes: compile the source's classes unprefixed (build/scan.css) and list them, so the
 *    rewrite knows which strings are classes → build/.classes.json;
 * 2. js: tsup, with a plugin that adds `sa:` to those classes in every source file;
 * 3. css: Tailwind with the `sa` prefix over the built JS, after scoping its preflight and
 *    Satin's base rules to Satin's elements;
 * 4. vars: `--x` → `--sa-x` in the CSS and the JS for every theme variable Tailwind prefixed,
 *    so Satin's own CSS, arbitrary values, inline styles and themeCss() all point at them;
 * 5. check: no class left unprefixed in the built JS.
 *
 *   node build/styles.mjs classes | css
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createRequire } from 'node:module'
import postcss from 'postcss'
import { PREFIX, declaredThemeVars, prefixThemeVars, scopeRules, utilityClasses } from './prefix.mjs'

const require = createRequire(import.meta.url)
const tailwind = (input, output, minify) =>
  execFileSync('npx', ['tailwindcss', '-i', input, '-o', output, ...(minify ? ['--minify'] : [])], { stdio: ['ignore', 'ignore', 'inherit'] })

const files = (dir, ext) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f)
    return statSync(p).isDirectory() ? files(p, ext) : p.endsWith(ext) ? [p] : []
  })

const step = process.argv[2]

if (step === 'classes') {
  tailwind('build/scan.css', 'build/.scan.out.css')
  const classes = [...utilityClasses(readFileSync('build/.scan.out.css', 'utf8'))].sort()
  writeFileSync('build/.classes.json', JSON.stringify(classes))
  console.log(`${classes.length} classes to prefix`)
}

if (step === 'css') {
  // Preflight and base rules, scoped, without their own @layer (styles.css puts them in base).
  const preflight = readFileSync(require.resolve('tailwindcss/preflight.css'), 'utf8')
  const base = readFileSync('src/styles/base.css', 'utf8')
  const unlayer = (css) => {
    const root = postcss.parse(css)
    root.walkAtRules('layer', (a) => (a.nodes ? a.replaceWith(a.nodes) : a.remove()))
    return root.toString()
  }
  writeFileSync('build/.preflight.css', `/* Generated by build/styles.mjs: Tailwind's preflight and Satin's base rules, scoped. */\n${scopeRules(unlayer(preflight))}\n${scopeRules(unlayer(base))}\n`)

  tailwind('build/styles.css', 'dist/styles.css', true)

  const css = readFileSync('dist/styles.css', 'utf8')
  const declared = declaredThemeVars(css)
  // Not Tailwind theme variables, but shadcn/ui apps define them too: Satin's become --sa-* as well.
  for (const name of ['radius', 'chart-1', 'chart-2', 'chart-3', 'chart-4', 'chart-5']) declared.add(name)
  writeFileSync('dist/styles.css', prefixThemeVars(css, declared))
  let touched = 0
  for (const f of files('dist', '.js')) {
    const js = readFileSync(f, 'utf8')
    const next = prefixThemeVars(js, declared)
    if (next !== js) (writeFileSync(f, next), touched++)
  }
  console.log(`styles.css: ${declared.size} theme variables as --${PREFIX}-*, ${touched} JS files pointed at them`)

  // A string made only of Satin classes, none prefixed, is a class list the rewrite didn't
  // reach (a computed name, an unusual place): it would render unstyled. Fail on it.
  const classes = new Set(JSON.parse(readFileSync('build/.classes.json', 'utf8')))
  const missed = []
  for (const f of files('dist', '.js')) {
    const js = readFileSync(f, 'utf8')
    for (const m of js.matchAll(/(["'`])((?:(?!\1)[^\\\n$]|\\.)*)\1/g)) {
      const tokens = m[2].trim().split(/\s+/).filter(Boolean)
      if (!tokens.length || !tokens.every((t) => classes.has(t))) continue
      if (!tokens.some((t) => /[-:[]/.test(t))) continue
      // CSS keywords that happen to be class names too (WAAPI easing).
      if (/^ease-(in|out|in-out)$/.test(m[2])) continue
      missed.push(`${m[2]}  (${f})`)
    }
  }
  if (missed.length) {
    console.error(`Class lists left unprefixed in dist:\n  ${missed.join('\n  ')}`)
    process.exit(1)
  }
}
